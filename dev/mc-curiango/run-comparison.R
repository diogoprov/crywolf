# Phase 1 of the sheepdog + crywolf integration on the curiango data:
# Monte Carlo propagation of the classifier calibration (custom classifier,
# export of sheepdog with calibration_draws.parquet). Versions of the
# detection histories from fp_draws_data(rule = "sample"), fitted with
# fp_occu_mc() with a constant false-positive rate and with one that depends
# on the conditions of the night. Answers:
#   (1) how many versions (M) are needed: the pooled estimates of the first
#       10, 20, 30 and 50 versions are compared (nested);
#   (2) do the false positives left after the calibration depend on the
#       conditions of the night (fp = ~ 1 against fp = ~ temp + rh), as at
#       a classifier threshold of 0.2 (vignette("threshold"))?
# Needs the export of sheepdog#39 or later (one prediction per minute, a
# calibration on minutes); an earlier export repeated each minute's score
# on every row.
# Sites of the model: nights at each recorder (night_site_id), as in
# vignette("markov"). 2 x M fits of 4 chains, 4 fits at a time (16 cores);
# about 6 minutes per fit, so 2.5 to 3 hours with M = 50 (estimate from a
# smoke run with 200 + 200 iterations).
# Run from the package root, with crywolf >= 1.9.0.9000 installed:
#   M=50 WORKERS=4 Rscript dev/mc-curiango/run-comparison.R <export folder>
# Output: dev/mc-curiango/results.rds, or the file named by OUT (for the
# sensitivity run with a calibration by month, OUT=results-season.rds).
# Do not edit this file while it runs.
library(crywolf)
dir <- commandArgs(TRUE)[1]
M <- as.integer(Sys.getenv("M", "50"))
workers <- as.integer(Sys.getenv("WORKERS", "4"))
iter <- as.integer(Sys.getenv("ITER", "1000"))
out_dir <- file.path("dev", "mc-curiango")
out_file <- Sys.getenv("OUT", "results.rds")

x <- suppressMessages(fp_read_sheepdog(dir, species = "nyc_alb"))
cov <- utils::read.csv(file.path(dir, "curiango_covariates.csv"),
                       colClasses = c(site = "character", occasion_id = "character",
                                      night_site_id = "character"))
zs <- function(v) as.numeric(scale(v))
occ <- merge(x$occasions[c("site", "occasion_id")], cov, by = c("site", "occasion_id"))
nights <- occ[!duplicated(occ$night_site_id), c("night_site_id", "temp", "rh", "moon")]
nights$temp <- zs(nights$temp)
nights$rh <- zs(nights$rh)
nights$moon <- zs(log(nights$moon))
occ$bio <- zs(occ$bio)
occ$aci <- zs(occ$aci)
occ <- occ[c("site", "occasion_id", "night_site_id", "bio", "aci")]

t0 <- Sys.time()
versions <- fp_draws_data(x, n_draws = M, seed = 1, occasions = occ, sites = nights,
                          site = "night_site_id")
crywolf::fp_compile()
future::plan(future::multisession, workers = workers)
fit <- function(fp) {
  t1 <- Sys.time()
  m <- fp_occu_mc(versions, occ = ~ temp + rh + moon, det = ~ bio + aci, fp = fp,
                  chains = 4, parallel_chains = 4, threads_per_chain = 1,
                  iter_warmup = iter, iter_sampling = iter, seed = 1,
                  parallel = TRUE, refresh = 0, show_messages = FALSE)
  m$minutes <- as.numeric(difftime(Sys.time(), t1, units = "mins"))
  m
}
res <- list(fp_constant = fit(~ 1), fp_temp_rh = fit(~ temp + rh))

# pooled estimates of the first k versions, from the per-fit summaries
# (law of total variance, as summary.fp_occu_mc())
nested <- purrr::imap(res, function(m, model) {
  purrr::map(intersect(c(10, 20, 30, 50), seq_along(m$summaries)), function(k) {
    s <- purrr::list_rbind(m$summaries[seq_len(k)])
    purrr::map(split(s, s$variable), function(g) {
      between <- mean((g$mean - mean(g$mean))^2)
      data.frame(model = model, M = k, variable = g$variable[1], mean = mean(g$mean),
                 sd = sqrt(mean(g$sd^2) + between),
                 share_between = between / (mean(g$sd^2) + between))
    }) |> purrr::list_rbind()
  }) |> purrr::list_rbind()
}) |> purrr::list_rbind()

out <- list(summary = purrr::map(res, function(m) summary(m)$table),
            nested = nested,
            diagnostics = purrr::map(res, "diagnostics"),
            minutes = purrr::map_dbl(res, "minutes"),
            detection_rate = purrr::map_dbl(versions, function(d) mean(d$auto$y)),
            M = M, iter = iter, hours = as.numeric(difftime(Sys.time(), t0, units = "hours")))
dir.create(out_dir, showWarnings = FALSE)
out$export <- dir
saveRDS(out, file.path(out_dir, if (M < 10) paste0("smoke-", out_file) else out_file))
print(out$summary, digits = 3)
print(out$minutes)
